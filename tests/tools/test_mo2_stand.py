def test_cli_writes_report(fake):
    fake.mod("A", {"gamedata/scripts/a.script": "a"})
    fake.mod("B", {"gamedata/scripts/a.script": "b"})
    write(fake.mo2 / "profiles" / "P" / "modlist.txt", "+B\n+A\n")
    core = write(fake.root / "repo" / "gamedata" / "scripts" / "coop_main.script", "core").parents[1]
    rep = fake.root / "report.txt"
    report = ms.main(["--mo2", str(fake.mo2), "--profile", "P", "--game", str(fake.game), "--out", str(fake.out),
                      "--layer-top", f"gamedata={core}", "--report", str(rep)])
    assert (fake.out / "gamedata" / "scripts" / "a.script").read_text(encoding="utf-8") == "b"
    assert (fake.out / "gamedata" / "scripts" / "coop_main.script").exists()
    text = rep.read_text(encoding="utf-8")
    assert "gamedata/scripts/a.script" in text
    assert f"files       {report.files}" in text
