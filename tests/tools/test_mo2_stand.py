# --- links, copies, never writing into the originals


def test_runtime_written_files_are_copies(fake):
    write(fake.game / "fsgame.ltx", "fs")
    fake.mod("A", {
        "gamedata/configs/axr_options.ltx": "opt",
        "gamedata/awr_table.txt": "awr",
        "appdata/gloss.ltx": "gloss",
        "gamedata/configs/plugins/p.ltx": "p",
        "gamedata/scripts/s.script": "s",
        "bin/ReShade.ini": "reshade",
        "bin/dxgi.log": "log",
        "bin/dxgi.dll": "dll",
    })
    fake.run(["A"])
    out = fake.out
    for rel in ("fsgame.ltx", "gamedata/configs/axr_options.ltx", "gamedata/awr_table.txt", "appdata/gloss.ltx",
                "bin/ReShade.ini", "bin/dxgi.log"):
        src = (fake.game if rel == "fsgame.ltx" else fake.mods / "A") / rel
        assert (out / rel).read_text(encoding="utf-8") == src.read_text(encoding="utf-8"), rel
        assert not os.path.samefile(out / rel, src), rel
    for rel in ("gamedata/configs/plugins/p.ltx", "gamedata/scripts/s.script", "bin/dxgi.dll"):
        assert os.path.samefile(out / rel, fake.mods / "A" / rel), rel


