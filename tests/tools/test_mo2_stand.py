from pathlib import Path

import pytest

import mo2_stand as ms


def write(path: Path, text: str = "x") -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


class FakeMo2:
    """A game folder, an MO2 instance (mods, overwrite, one profile) and a stand folder, all under one temp dir."""

    def __init__(self, root: Path):
        self.root = root
        self.game = root / "game"
        self.mo2 = root / "mo2"
        self.mods = self.mo2 / "mods"
        self.overwrite = self.mo2 / "overwrite"
        self.out = root / "out"
        for d in (self.game, self.mods, self.overwrite):
            d.mkdir(parents=True)

    def mod(self, name: str, files: dict[str, str]) -> Path:
        for rel, text in files.items():
            write(self.mods / name / rel, text)
        return self.mods / name

    def run(self, mods: list[str], bottom=(), tops=()) -> "ms.Report":
        layers = ms.build_layers(self.game, list(bottom), self.mods, mods, self.overwrite, list(tops))
        return ms.materialize(layers, self.out)


