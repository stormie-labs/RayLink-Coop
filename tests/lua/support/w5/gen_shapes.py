# Anomaly Coop W5 test tool: shapes of stock scripts (top-level functions, tables, classes and methods)
# -> stock_shapes.lua for the all-groups stub run (tests/lua/test_w5.lua). Not shipped.
#   python tests/lua/support/w5/gen_shapes.py      (stock scripts: ../anomaly-ref/unpacked/scripts, override ANOMALY_REF)
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
REF = os.path.join(os.environ.get("ANOMALY_REF", os.path.join(ROOT, "..", "anomaly-ref", "unpacked")), "scripts")
EXE = os.path.join(ROOT, "engine", "gamedata", "scripts")
files = {}
for d in (REF, EXE):  # modded-exes overrides stock
    for n in os.listdir(d):
        if n.lower().endswith(".script"):
            files[n[:-7].lower()] = os.path.join(d, n)
re_fn = re.compile(r"^function\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(")
re_tfn = re.compile(r"^function\s+([A-Za-z_][A-Za-z0-9_]*)\s*[.:]\s*([A-Za-z_][A-Za-z0-9_]*)\s*\(")
re_cls = re.compile(r"^\s*class\s*\"([A-Za-z_][A-Za-z0-9_]*)\"\s*(?:\(\s*([A-Za-z_][A-Za-z0-9_.]*)\s*\))?")
re_tbl = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*\{")
re_var = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*([^{].*)$")
out = ["-- generated by gen_shapes.py: stock script shapes", "STOCK = {"]
rets = []
re_ret = re.compile(r"^\s*return\s+[^\s;-]")
def q(s): return '"' + s + '"'
for mod in sorted(files):
    try:
        src = open(files[mod], encoding="cp1251", errors="replace").read()
        # block comments do not define anything (e.g. _g.script's commented-out wait())
        src = re.sub(r"--\[(=*)\[.*?\]\1\]", "", src, flags=re.S)
    except Exception as e:
        continue
    fns, tbls, classes, vars_ = [], {}, {}, []
    cur = None
    for line in src.splitlines():
        if cur and re_ret.match(line) and not re.match(r"^\s*return\s+end", line):
            rets.append(cur)
        if line.startswith("end"):
            cur = None
        m = re_cls.match(line)
        if m:
            classes.setdefault(m.group(1), {"base": m.group(2), "m": []}); continue
        m = re_tfn.match(line)
        if m:
            a, b = m.group(1), m.group(2)
            if a in classes:
                classes[a]["m"].append(b); cur = "%s.%s:%s" % (mod, a, b)
            else:
                tbls.setdefault(a, []).append(b); cur = "%s.%s.%s" % (mod, a, b)
            continue
        m = re_fn.match(line)
        if m:
            fns.append(m.group(1)); cur = "%s.%s" % (mod, m.group(1)); continue
        m = re_tbl.match(line)
        if m: tbls.setdefault(m.group(1), []); continue
        m = re_var.match(line)
        if m and m.group(1) not in ("local",): vars_.append(m.group(1))
    parts = []
    parts.append("f={" + ",".join(q(f) for f in sorted(set(fns))) + "}")
    parts.append("t={" + ",".join("%s={%s}" % (k, ",".join(q(x) for x in sorted(set(v)))) for k, v in sorted(tbls.items()) if re.match(r"^[A-Za-z_]\w*$", k)) + "}")
    parts.append("c={" + ",".join("%s={b=%s,m={%s}}" % (k, q(v["base"]) if v["base"] else "nil", ",".join(q(x) for x in sorted(set(v["m"])))) for k, v in sorted(classes.items())) + "}")
    parts.append("v={" + ",".join(q(x) for x in sorted(set(vars_))) + "}")
    out.append("\t[%s] = { %s }," % (q(mod), ", ".join(parts)))
out.append("}")
out.append("STOCK_RETURNS = {")
for r in sorted(set(rets)): out.append('	["%s"] = true,' % r)
out.append("}")
open(os.path.join(HERE, "stock_shapes.lua"), "w", encoding="utf-8", newline=chr(10)).write(chr(10).join(out) + chr(10))
print(len(files), "stock scripts")
