local M = { W16 = W16, W18 = W18 }

-- width of a string in the units of the 4:3 UI (bytes of cp1251; an unknown byte is 0 wide)
function M.width(font, text)
	local total = 0
	for i = 1, #text do total = total + (font[text:byte(i)] or 0) end
	return total
end

-- number of lines a text takes in a box `box` units wide (greedy wrap at spaces, as a text window in complex mode does)
function M.lines(font, text, box)
	local n, cur = 1, 0
	local space = font[32] or 0
	for word in text:gmatch("%S+") do
		local w = M.width(font, word)
		if cur == 0 then
			cur = w
		elseif cur + space + w <= box then
			cur = cur + space + w
		else
			n = n + 1
			cur = w
		end
	end
	return n
end

return M
