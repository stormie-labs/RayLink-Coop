-- Anomaly Coop: generates gamedata\configs\coop_route_gamma.ltx (ruling F2-28): GAMMA scripts without a route rule
-- that call world functions and, since F2 T10, would run on a client get "= host" (their behaviour before T10).
-- Usage (repository root; tools\test_lua.cmd builds the runner):
--   set GAMMA_SCRIPTS=E:\AnomalyCoopGamma\gamedata\scripts && temp\lua\runlua.exe tools\gen_route_gamma.lua
-- Method (the F2 T10 survey, temp\f2t10):
--   1. every literal RegisterScriptCallback("<callback>", ...) in GAMMA's *.script and *.lua (all folders);
--   2. a (script, callback) pair runs on a client NOW when the engine's router (coop_routes.h through coop_native, the
--      rules of every configs\coop_route*.ltx except this output) routes it to owner or view; it ran BEFORE T10 when
--      the old Lua filter did: it keyed a file by its base name, took that name's [route_scripts] rule (the same
--      entries; old blocked = host now), treated a name without a rule as host, and applied the forced callbacks;
--   3. a script with a pair that runs now and did not before, whose file calls one of the WORLD functions below, and
--      that has no [route_scripts] rule of its own, is written as "<script key> = host".
-- Rerun after a GAMMA update or after a change of the other coop_route*.ltx, then run tools\test_lua.cmd.
local BS = string.char(92)
local OUT = "gamedata" .. BS .. "configs" .. BS .. "coop_route_gamma.ltx"
local ROOT = os.getenv("GAMMA_SCRIPTS")
if not ROOT or ROOT == "" then
	print("set GAMMA_SCRIPTS to GAMMA's gamedata\\scripts folder, e.g. E:\\AnomalyCoopGamma\\gamedata\\scripts")
	os.exit(2)
end
ROOT = ROOT:gsub("^%s+", ""):gsub("%s+$", ""):gsub("[/\\]+$", "") -- cmd's "set X=... && ..." keeps the blank

ROUTE_SKIP_FILES = { ["coop_route_gamma.ltx"] = true }
dofile("tests/lua/support/stubs.d/route.lua")
route_stub_load()
if #ROUTE_ERRORS > 0 then
	print("coop_route*.ltx has errors: " .. table.concat(ROUTE_ERRORS, " | "))
	os.exit(3)
end

-- Calls that change the world (plain, case-sensitive substrings of the file).
local WORLD = { "alife():create", "alife_create", "alife():release", "alife_release", "create_squad", "SIMBOARD",
	"give_info", "disable_info", "set_community_goodwill", "change_faction_relations", "set_relation", "transfer_item",
	":kill(" }

-- The [route_scripts] rule of a name: the exact key, else the longest prefix (a key ending in *); nil without one.
local function rule_of(name)
	local d = ROUTE_SCRIPT_RULES[name]
	if d then return d end
	local best
	for key, dom in pairs(ROUTE_SCRIPT_RULES) do
		if key:sub(-1) == "*" then
			local p = key:sub(1, -2)
			if name:sub(1, #p) == p and (not best or #p > #best[1]) then best = { p, dom } end
		end
	end
	return best and best[2] or nil
end

local function ran_before(base, callback)
	local forced = ROUTE_FORCED[callback:lower()]
	if forced == "host" then return false end
	if forced == "view" then return true end
	local d = rule_of(base) or "host"
	return d == "owner" or d == "view"
end

local files = {}
local pipe = assert(io.popen('dir /s /b "' .. ROOT .. BS .. '*.script" "' .. ROOT .. BS .. '*.lua" 2>nul'))
for line in pipe:lines() do
	line = line:gsub("\r", "")
	if line ~= "" then files[#files + 1] = line end
end
pipe:close()
table.sort(files, function(a, b) return a:lower() < b:lower() end)
if #files == 0 then
	print("no *.script / *.lua under " .. ROOT)
	os.exit(4)
end

local rows, pairs_total, newly_total, has_rule = {}, 0, 0, {}
for _, path in ipairs(files) do
	local fh = io.open(path, "rb")
	local src = fh and fh:read("*a") or ""
	if fh then fh:close() end
	local key = coop_native.script_key("@" .. path)
	local base = (path:match("([^\\/]+)%.[sS][cC][rR][iI][pP][tT]$") or path:match("([^\\/]+)%.[lL][uU][aA]$") or "?"):lower()
	local seen, newly = {}, {}
	for cb in src:gmatch("RegisterScriptCallback%s*%(%s*[\"']([%w_]+)[\"']") do
		if not seen[cb] then
			seen[cb] = true
			pairs_total = pairs_total + 1
			local runs_now = coop_native.runs_here(coop_native.route(cb, key), false)
			if runs_now and not ran_before(base, cb) then newly[#newly + 1] = cb end
		end
	end
	if #newly > 0 then
		newly_total = newly_total + 1
		local calls = 0
		for _, w in ipairs(WORLD) do
			local at = 1
			while true do
				local s, e = src:find(w, at, true)
				if not s then break end
				calls = calls + 1
				at = e + 1
			end
		end
		if calls > 0 then
			if rule_of(key) then
				has_rule[#has_rule + 1] = key .. " (" .. rule_of(key) .. ")"
			else
				rows[#rows + 1] = { key = key, calls = calls, cbs = newly }
			end
		end
	end
end
table.sort(rows, function(a, b) return a.key < b.key end)
table.sort(has_rule)

local out = {}
local function add(s) out[#out + 1] = s end
add("; Anomaly Coop - GAMMA world scripts that stay on the host (ruling F2-28), read by the engine after")
add("; configs\\coop_route.ltx like every coop_route_*.ltx (same sections and rules, see there).")
add(";")
add("; GENERATED by tools\\gen_route_gamma.lua - do not edit by hand, rerun it after a GAMMA update (or after a change of")
add("; the other coop_route*.ltx) and run tools\\test_lua.cmd:")
add(";   set GAMMA_SCRIPTS=E:\\AnomalyCoopGamma\\gamedata\\scripts && temp\\lua\\runlua.exe tools\\gen_route_gamma.lua")
add("; Since F2 T10 a script without a rule follows its callback (actor_* owner: runs on a client, review R5 I4). Before,")
add("; a script without a rule was host. A script below has no rule of its own, registers a callback that runs on a client")
add("; now and did not before, and calls a world function (alife():create / alife_create / ..._release, create_squad,")
add("; SIMBOARD, give_info / disable_info, relations, transfer_item, :kill): until the call router (F2 T12) gates such")
add("; calls, a client running it could duplicate items, so it keeps its old behaviour. A client that needs one of them")
add("; shows it in coop_status ([coop] routes: most skipped); give that script its own rule in another coop_route_*.ltx")
add("; (it then drops out of this list on the next run).")
add(string.format("; Generated %s from %s:", os.date("%Y-%m-%d"), ROOT))
add(string.format(";   %d files, %d (script, callback) registrations, %d scripts that run on a client since T10;",
	#files, pairs_total, newly_total))
add(string.format(";   %d of them call world functions, %d of those already have a rule (%s).", #rows + #has_rule,
	#has_rule, #has_rule > 0 and table.concat(has_rule, ", ") or "none"))
add("; Comment of a line: world calls in the file | the callbacks that would run on a client.")
add("")
add("[route_scripts]")
for _, r in ipairs(rows) do
	local cbs = {}
	for i = 1, math.min(#r.cbs, 4) do cbs[i] = r.cbs[i] end
	local more = #r.cbs > 4 and (" +" .. (#r.cbs - 4)) or ""
	add(string.format("%-40s = host   ; %3d | %s%s", r.key, r.calls, table.concat(cbs, " "), more))
end
add("")

local fh = assert(io.open(OUT, "wb"))
fh:write(table.concat(out, "\n"))
fh:close()
print(string.format("%s: %d scripts = host (%d files, %d registrations, %d run on a client since T10, %d with world calls, "
	.. "%d of those have a rule)", OUT, #rows, #files, pairs_total, newly_total, #rows + #has_rule, #has_rule))
